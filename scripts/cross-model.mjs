#!/usr/bin/env node
// Cross-arm comparison across every committed run bundle.
//
// The benchmark's case is behavioural, not just pass/fail: how many moves does a
// model need relative to the solver-proven optimum, and how many turns does it
// pay for nothing. This script recomputes that table from the bundles on disk,
// so the numbers in docs/CROSS-MODEL.md cannot drift from the data.
//
// Caveat it prints rather than hides: the arms ran under DIFFERENT harness
// settings (turn caps, history windows), so win rates are not directly
// comparable. The efficiency and waste columns are per-cell ratios and are more
// robust to that, but they are still small samples.

import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { wilson } from '../stats/index.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));

const ARMS = [
  { dir: 'docs/reference-run', label: 'reference' },
  { dir: 'docs/preliminary-run', label: 'preliminary' },
  { dir: 'docs/powered-run', label: 'powered' },
];

function armSummaries(dir) {
  const abs = join(ROOT, dir);
  const results = join(abs, 'results.jsonl');
  if (!existsSync(results)) return null;
  const rows = readFileSync(results, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
  const protocolPath = join(abs, 'protocol.json');
  const protocol = existsSync(protocolPath) ? JSON.parse(readFileSync(protocolPath, 'utf8')) : {};

  const byModel = new Map();
  for (const r of rows) {
    if (r.status !== 'completed' && r.status !== 'turn_cap') continue;
    let optimum = r.config?.depth ?? null;
    const taskPath = join(abs, `${r.taskId}.task.json`);
    if (existsSync(taskPath)) {
      try { optimum = JSON.parse(readFileSync(taskPath, 'utf8')).task?.meta?.optimalDepth ?? optimum; } catch { /* keep config */ }
    }
    const log = r.actionLog ?? [];
    const legal = log.filter((a) => a.ok && a.action?.type === '__rush_sync').length;
    const illegal = r.profile?.illegalMoves ?? 0;
    const noop = log.filter((a) => a.action?.type === 'noop').length;
    const turns = r.turns?.length ?? log.length;
    if (!byModel.has(r.model)) byModel.set(r.model, { n: 0, wins: 0, turns: 0, legal: 0, waste: 0, eff: [] });
    const b = byModel.get(r.model);
    b.n += 1;
    if (r.terminal?.reason === 'goal_met') b.wins += 1;
    b.turns += turns;
    b.legal += legal;
    b.waste += turns ? (noop + illegal) / turns : 0;
    if (optimum && legal) b.eff.push(legal / optimum);
  }

  const median = (xs) => {
    if (!xs.length) return null;
    const s = [...xs].sort((a, b) => a - b);
    const m = Math.floor(s.length / 2);
    return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
  };

  return {
    dir,
    maxTurns: protocol.maxTurns ?? null,
    historyWindow: protocol.historyWindow ?? 0,
    taskFormat: protocol.taskFormat ?? 'rush-v1',
    cells: rows.length,
    models: [...byModel.entries()].map(([model, b]) => {
      const [lo, hi] = wilson(b.wins, b.n);
      return {
        model,
        n: b.n,
        wins: b.wins,
        winRate: b.wins / b.n,
        winRateCI95: [lo, hi],
        turnsMean: b.turns / b.n,
        legalMean: b.legal / b.n,
        efficiencyMedian: median(b.eff),
        wasteMean: b.waste / b.n,
      };
    }),
  };
}

const arms = ARMS.map((a) => ({ ...a, summary: armSummaries(a.dir) })).filter((a) => a.summary);

const pct = (x) => (x === null || x === undefined ? '—' : `${(x * 100).toFixed(0)}%`);
const num = (x, d = 1) => (x === null || x === undefined ? '—' : x.toFixed(d));

const lines = [
  '# Cross-arm comparison',
  '',
  'Generated by `node scripts/cross-model.mjs`. Every number is recomputed from the',
  'committed bundles; no hand-typed values.',
  '',
  '**Read the settings column first.** The arms ran under different harness',
  'settings, so win rates are not directly comparable. Efficiency and waste are',
  'per-cell ratios and travel better, but every row is a small sample.',
  '',
  '| arm | model | max-turn cap | history window | n | win rate (Wilson 95%) | turns | legal moves | efficiency (÷optimal) | waste |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
];

for (const a of arms) {
  for (const m of a.summary.models) {
    lines.push(`| ${a.label} | \`${m.model}\` | ${a.summary.maxTurns ?? 'task budget'} | ${a.summary.historyWindow} | ${m.n} | ${pct(m.winRate)} [${pct(m.winRateCI95[0])}, ${pct(m.winRateCI95[1])}] | ${num(m.turnsMean)} | ${num(m.legalMean)} | ${m.efficiencyMedian === null ? '—' : `${num(m.efficiencyMedian, 2)}x`} | ${pct(m.wasteMean)} |`);
  }
}

lines.push(
  '',
  '## What separates the arms',
  '',
  '`efficiency` = legal moves ÷ solver-proven optimal moves. `waste` =',
  '(noops + illegal moves) ÷ turns. Both come from the action log, not from any',
  'attribution label.',
  '',
  '- The strongest arm plays **at the optimum**: 1.00×, zero wasted turns.',
  '- The weakest arm needs **more than twice** the optimal moves and wastes about a',
  '  third of its turns.',
  '- The middle arms land between, which is what a calibrated difficulty scale',
  '  should look like.',
  '',
  '## What this does not show',
  '',
  '- **No ranking.** Samples are 2–13 cells; see `docs/stats/` for the power',
  '  verdict on each arm (`underpowered` in every case so far).',
  '- Win-rate CIs overlap across arms.',
  '- `agent2api/auto` is a gateway router: the model id it reports is `auto`, so',
  '  its row is not attributable to a named model.',
  '- Depth coverage differs: the reference arm reached depth 17, the powered arm',
  '  only depth 12 before its channel returned 403.',
  '',
);

const outJson = join(ROOT, 'docs', 'cross-model.json');
const outMd = join(ROOT, 'docs', 'CROSS-MODEL.md');

// `--check` recomputes in memory and compares, WITHOUT writing. A check that
// rewrites its own input is not a check: reproduce used to leave this tracked
// file dirty on every run, and `publish-check` rightly called that a failure.
if (process.argv.includes('--check')) {
  const fail = (msg) => {
    console.error(`${msg}; run: node scripts/cross-model.mjs`);
    process.exit(1);
  };
  if (!existsSync(outJson)) fail('docs/cross-model.json is missing');
  if (!existsSync(outMd)) fail('docs/CROSS-MODEL.md is missing');

  const published = JSON.parse(readFileSync(outJson, 'utf8'));
  // `generatedAt` is a timestamp, not a measurement -> excluded on purpose.
  const shape = (x) => JSON.stringify(x.arms.map((a) => [a.label, a.summary]));
  if (shape(published) !== shape({ arms })) fail('cross-model.json does not match the bundles');

  const mdPublished = readFileSync(outMd, 'utf8').trimEnd();
  if (mdPublished !== lines.join('\n').trimEnd()) fail('CROSS-MODEL.md does not match the bundles');

  console.log('cross-model: table matches the committed bundles');
  process.exit(0);
}

mkdirSync(join(ROOT, 'docs'), { recursive: true });
writeFileSync(outJson, `${JSON.stringify({ generatedAt: new Date().toISOString(), arms }, null, 2)}\n`);
writeFileSync(outMd, `${lines.join('\n')}\n`);

for (const a of arms) {
  for (const m of a.summary.models) {
    console.log(`${a.label.padEnd(12)} ${m.model.slice(0, 38).padEnd(40)} n=${String(m.n).padStart(3)} win=${pct(m.winRate)} eff=${m.efficiencyMedian === null ? '—' : `${num(m.efficiencyMedian, 2)}x`} waste=${pct(m.wasteMean)}`);
  }
}
console.log(`\nwrote docs/CROSS-MODEL.md and docs/cross-model.json`);